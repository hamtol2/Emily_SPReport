import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const dir=import.meta.dirname;
const data=JSON.parse(fs.readFileSync(dir+'/source-data.json','utf8'));
const source=JSON.parse(fs.readFileSync(dir+'/verification-source.json','utf8'));
const js=fs.readFileSync(dir+'/app.js','utf8').split("for(const el of ['start'")[0];
const elements=new Map();
const document={getElementById:(id)=>{if(!elements.has(id))elements.set(id,{value:'',innerHTML:'',textContent:''});return elements.get(id);}};
const context=vm.createContext({Intl,Date,Set,Map,Number,String,Array,Object,Math,Error,JSON,document});
vm.runInContext(js+';globalThis.api={parseModel,metrics,numeric,compact,shortageValue,categoryShortages,endShortage};',context);
const {parseModel,metrics,numeric,compact,shortageValue,categoryShortages,endShortage}=context.api;
const m=parseModel(data);
assert.equal(m.products.length,source.products);
assert.equal(m.months.length,12);
assert.equal(m.months[0].key,'2024-02');
assert.equal(m.months.at(-1).key,'2025-01');
for(let i=0;i<m.months.length;i++){
  const neg=m.products.filter(p=>p.monthly[i].closing<0);
  assert.equal(neg.length,source.monthlyNegativeCounts[i]);
  assert.ok(Math.abs(neg.reduce((s,p)=>s-p.monthly[i].closing,0)-source.monthlyNegativeQuantity[i])<.001);
}
const x=m.products.map(p=>metrics(p,[0,1,2]));
assert.equal(x.filter(p=>p.peak>0).length,source.firstThreeUnique);
assert.ok(Math.abs(x.reduce((s,p)=>s+p.peak,0)-source.firstThreeMaxSum)<.001);
assert.equal(m.products.find(p=>p.row===65).monthly[0].closing,-451);
assert.equal(m.products.find(p=>p.sku==='TBD0051').stage,'canceled');
assert.equal(numeric({A:{v:null,f:true,t:'n'}},'A',true),null);
assert.equal(numeric({},'A',true),0);
assert.equal(numeric({A:{v:'#REF!',f:true,t:'e'}},'A',true),null);
assert.equal(numeric({A:{v:0,f:true,t:'n'}},'A',true),0);
const bad=structuredClone(data);bad.sheets.CMMF_Tefal['9000']=structuredClone(bad.sheets.CMMF_Tefal['65']);
assert.throws(()=>parseModel(bad),/중복 SKU/);
const missing=structuredClone(data);missing.sheets.CMMF_Tefal['65'].DJ.v=null;
const badProduct=parseModel(missing).products.find(p=>p.row===65);
assert.equal(badProduct.monthly[0].closing,null);
assert.equal(metrics(badProduct,[0]).missing,true);
assert.equal(parseModel(compact(data)).products.length,source.products);
assert.equal(shortageValue({closing:-451}),451);
assert.equal(shortageValue({closing:24}),0);
assert.equal(shortageValue({closing:null}),null);
for(let i=0;i<12;i++){
  assert.equal(endShortage(m.products,i),source.monthlyNegativeQuantity[i]);
  assert.equal(categoryShortages(m.products,i).reduce((s,g)=>s+g.quantity,0),source.monthlyNegativeQuantity[i]);
}
context.fixture=data;
vm.runInContext("model=parseModel(fixture);$('start').value='0';$('end').value='2';$('category').value='KITCHENWARE & DINNER';$('fl1').value='KITCHEN KNIVES';render();",context);
const table=elements.get('shortageTable').innerHTML;
assert.ok(table.includes('대상 채널')&&table.includes('Costco'));
assert.ok(!table.includes('PM')&&!table.includes('최초 부족')&&!table.includes('최대 부족'));
assert.ok(table.includes('451')&&!table.includes('>-451<'));
assert.ok(elements.get('newTable').innerHTML.includes('출시 월¹'));
assert.ok(elements.get('eolTable').innerHTML.includes('EOL 상태'));
for(const key of ['newTable','eolTable'])assert.ok(!elements.get(key).innerHTML.includes('PM'));
const csv=vm.runInContext("csvContent('shortage')",context);
assert.ok(csv.includes('FL1')&&!csv.includes('PM')&&!csv.includes('최초 부족')&&!csv.includes('최대 부족'));
const filtered=vm.runInContext('filtered()',context);
assert.ok(filtered.length>0&&filtered.every(p=>p.category==='KITCHENWARE & DINNER'&&p.family==='KITCHEN KNIVES'));
assert.equal(vm.runInContext('shownNew.every(r=>r.p.stage!=="out") && shownEol.every(r=>r.p.stage==="out")',context),true);
console.log(JSON.stringify({result:'PASS',sku:m.products.length,months:m.months.length,sourceReconciled:'all 12 months',firstThreeUnique:source.firstThreeUnique,firstThreeMaxSum:source.firstThreeMaxSum,stages:Object.fromEntries([...new Set(m.products.map(p=>p.stage))].map(s=>[s,m.products.filter(p=>p.stage===s).length])),issues:m.issues},null,2));
